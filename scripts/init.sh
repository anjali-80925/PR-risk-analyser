#!/bin/bash
set -uo pipefail

# ── PR Risk Analyser — Interactive Setup Wizard ──────────────────────────────
# Creates config.env in workspace root. Run once per team/project. Pure bash.

# ── Bootstrap (common.sh only — config doesn't exist yet) ────────────────────
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$SCRIPT_DIR/lib/common.sh"

CONFIG_FILE="$WORKSPACE_ROOT/config.env"

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "  PR Risk Analyser — Setup Wizard"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo ""

# ── Check existing config ─────────────────────────────────────────────────────
if [[ -f "$CONFIG_FILE" ]]; then
  log_warn "config.env already exists."
  read -rp "Overwrite? (y/n) [n]: " OVERWRITE
  if [[ "${OVERWRITE:-n}" != "y" ]]; then
    echo "Setup cancelled. Existing config kept."
    exit 0
  fi
fi

# ── Step 1: Git Provider ─────────────────────────────────────────────────────
log_step "Step 1/4 — Git Provider"
echo "  1) Bitbucket Server (on-premise)"
echo "  2) Bitbucket Cloud"
echo "  3) GitHub"
echo "  4) GitLab"
read -rp "Select [1-4]: " GIT_CHOICE

case "$GIT_CHOICE" in
  1) GIT_PROVIDER="bitbucket-server" ;;
  2) GIT_PROVIDER="bitbucket-cloud" ;;
  3) GIT_PROVIDER="github" ;;
  4) GIT_PROVIDER="gitlab" ;;
  *) log_error "Invalid choice"; exit 1 ;;
esac

echo ""
echo "Enter the base URL for your repos (everything before the repo name)."
echo "  Bitbucket Server: ssh://git@bitbucket.example.com:7999/PROJECT"
echo "  GitHub:           git@github.com:ORG"
echo "  GitLab:           git@gitlab.com:GROUP"
read -rp "Base URL: " REPO_BASE_URL
REPO_BASE_URL="${REPO_BASE_URL%/}"

if [[ -z "$REPO_BASE_URL" ]]; then
  log_error "Base URL is required."; exit 1
fi

# ── Step 2: Services ─────────────────────────────────────────────────────────
log_step "Step 2/4 — Services"
echo "Enter service names one per line (these must match repo names)."
echo "Press Enter on empty line to finish."
SVC_NAMES=()
while true; do
  read -rp "  Service: " SVC_NAME
  [[ -z "$SVC_NAME" ]] && break
  SVC_NAMES+=("$SVC_NAME")
done

if [[ ${#SVC_NAMES[@]} -eq 0 ]]; then
  log_error "At least one service is required."; exit 1
fi

SVC_MODE="manual"
SERVICES_LIST=$(IFS=','; echo "${SVC_NAMES[*]}")

# ── Step 3: JIRA ──────────────────────────────────────────────────────────────
log_step "Step 3/4 — JIRA Configuration"
echo "Enter your JIRA project key prefix (e.g., DBCCPMCMS, PROJ, MYTEAM)."
read -rp "Project key: " JIRA_KEY

if [[ -z "$JIRA_KEY" ]]; then
  log_error "JIRA project key is required."; exit 1
fi

# ── Step 4: Test Automation Repo ─────────────────────────────────────────────
log_step "Step 4/5 — Test Automation Repository"
echo "Enter the name of your test automation repo (same base URL as services)."
echo "  Example: my-automated-tests"
echo "  Leave blank to skip (test selection will be unavailable)."
read -rp "Test repo name: " TEST_REPOS

# ── Step 5: Performance ──────────────────────────────────────────────────────
log_step "Step 5/5 — Performance"
read -rp "Max parallel service scans [4]: " MAX_PARALLEL
MAX_PARALLEL="${MAX_PARALLEL:-4}"

# ── Write config.env ──────────────────────────────────────────────────────────
cat > "$CONFIG_FILE" << EOF
# ── PR Risk Analyser — Configuration ──────────────────────────────────────────
# Generated by: bash scripts/init.sh
# Docs: see readme.md

# ── Git Provider ──────────────────────────────────────────────────────────────
# Supported: bitbucket-server | bitbucket-cloud | github | gitlab
GIT_PROVIDER=$GIT_PROVIDER

# Base URL for repo cloning (SSH or HTTPS)
REPO_BASE_URL=$REPO_BASE_URL

# ── Services ──────────────────────────────────────────────────────────────────
# Discovery mode: manual (uses SERVICES list) | auto (scans workspace .git dirs)
SERVICE_DISCOVERY_MODE=$SVC_MODE

# Comma-separated repo names (used when SERVICE_DISCOVERY_MODE=manual)
SERVICES=$SERVICES_LIST

# ── JIRA ──────────────────────────────────────────────────────────────────────
# Project key prefix(es), comma-separated
JIRA_PROJECT_KEYS=$JIRA_KEY

# ── Test Automation Repo ──────────────────────────────────────────────────────
# Repo name of the automation test suite (URL = REPO_BASE_URL/TEST_REPOS)
# Leave blank to disable test selection (Mode 2)
TEST_REPOS=${TEST_REPOS:-}

# ── Performance ───────────────────────────────────────────────────────────────
MAX_PARALLEL=$MAX_PARALLEL
REF_CACHE_TTL=600
EOF

echo ""
log_ok "Configuration saved to: config.env"

# ── Clone all configured service repos now (so analysis never waits on clone) ─
log_step "Cloning all service repositories"
source "$SCRIPT_DIR/lib/load_config.sh"
clone_all_services

# ── Build symbol index for instant cross-repo lookups ─────────────────────
log_step "Building cross-repo symbol index (enables <2s impact analysis)"
# Use Windows Python for NTFS repos (os.walk via WSL is ~100x slower)
PYTHON_CMD="python3"
if command -v python.exe &>/dev/null; then
  PYTHON_CMD="python.exe"
elif command -v /mnt/c/Users/anl/scoop/apps/python/current/python.exe &>/dev/null; then
  PYTHON_CMD="/mnt/c/Users/anl/scoop/apps/python/current/python.exe"
fi
"$PYTHON_CMD" "$SCRIPT_DIR/lib/index_symbols.py" \
    --repos-dir "$SERVICE_REPOS_DIR" \
    --output "$SERVICE_REPOS_DIR/.symbol-index.json" || \
  echo "[WARN] Symbol index build failed — analysis will fall back to grep scan" >&2

echo ""
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "  Setup complete!"
echo ""
echo "  Next: Open VS Code → Copilot Chat → say:"
echo "    \"Analyze PROJ-123\""
echo ""
echo "  All service repos pre-cloned to .service-repos/"
echo "  Analysis will git fetch (not clone) on each run."
echo ""
if [[ -n "${TEST_REPOS:-}" ]]; then
  echo "  Test selection: enabled ($TEST_REPOS)"
else
  echo "  Test selection: skipped (no test repo configured)"
fi
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
